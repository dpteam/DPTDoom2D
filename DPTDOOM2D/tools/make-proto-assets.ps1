<#
.SYNOPSIS
    Regenerates DPTDOOM2D/Prototypes/ProtoAssets.cs from the .VGA files.

.DESCRIPTION
    The prototypes need a handful of 1995-era artwork containers, and nobody
    should have to keep binary files next to the source just to see a demo run.
    This script inlines them into C# as base64, so the exe is self-contained: no
    loose files, no copying step, and a fresh checkout plays the prototypes
    immediately.

    Base64 rather than a binary embedded resource on purpose - the data is then
    in the source that a reviewer reads, and there is no build step that can
    silently drop an asset.

    Source directory defaults to the reference tree, so the artwork still comes
    from the original archive and not from this repository's copy.

.PARAMETER Source
    Folder with the .VGA files. Default: refs/D2D_Also oldprog + TC artwork,
    already collected in DPTDOOM2D/Prototypes/Assets by tools/collect-proto-assets.ps1.

.PARAMETER Out
    Output C# file. Default: DPTDOOM2D/Prototypes/ProtoAssets.cs
#>
[CmdletBinding()]
param(
    [string]$Source,
    [string]$Out
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
if (-not $Source) { $Source = Join-Path $root 'Prototypes\Assets' }
if (-not $Out) { $Out = Join-Path $root 'Prototypes\ProtoAssets.cs' }

if (-not (Test-Path $Source)) { throw "no such folder: $Source" }

$files = Get-ChildItem $Source -Filter *.VGA | Sort-Object Name
if ($files.Count -eq 0) { throw "no .VGA files in $Source" }

$text = New-Object System.Text.StringBuilder

[void]$text.AppendLine('//')
[void]$text.AppendLine('// DPT.DOOM 2D - the artwork the prototypes draw with.')
[void]$text.AppendLine('// Copyright (C) 2026 DartPower Team. GPLv2.')
[void]$text.AppendLine('//')
[void]$text.AppendLine('// GENERATED by tools/make-proto-assets.ps1 - do not edit by hand.')
[void]$text.AppendLine('//')
[void]$text.AppendLine('// These are the original .VGA containers from the Doom2D-era tools (see')
[void]$text.AppendLine('// docs/PROTOTYPES.md for which program each one came from), inlined as base64')
[void]$text.AppendLine('// so a prototype runs without any files next to the exe.')
[void]$text.AppendLine('//')
[void]$text.AppendLine()
[void]$text.AppendLine('using System;')
[void]$text.AppendLine('using System.Collections.Generic;')
[void]$text.AppendLine()
[void]$text.AppendLine('namespace DPTDOOM2D.Prototypes')
[void]$text.AppendLine('{')
[void]$text.AppendLine('    /// <summary>')
[void]$text.AppendLine('    /// The prototype artwork, one base64 blob per container.')
[void]$text.AppendLine('    /// </summary>')
[void]$text.AppendLine('    internal static class ProtoAssets')
[void]$text.AppendLine('    {')
[void]$text.AppendLine('        private static Dictionary<string, string> blobs;')
[void]$text.AppendLine()
[void]$text.AppendLine('        /// <summary>Decoded container bytes, or null when the name is unknown.</summary>')
[void]$text.AppendLine('        public static byte[] Get(string fileName)')
[void]$text.AppendLine('        {')
[void]$text.AppendLine('            if (blobs == null) Build();')
[void]$text.AppendLine()
[void]$text.AppendLine('            string base64;')
[void]$text.AppendLine('            if (!blobs.TryGetValue(fileName, out base64)) return null;')
[void]$text.AppendLine()
[void]$text.AppendLine('            try')
[void]$text.AppendLine('            {')
[void]$text.AppendLine('                return Convert.FromBase64String(base64);')
[void]$text.AppendLine('            }')
[void]$text.AppendLine('            catch (FormatException)')
[void]$text.AppendLine('            {')
[void]$text.AppendLine('                return null;')
[void]$text.AppendLine('            }')
[void]$text.AppendLine('        }')
[void]$text.AppendLine()
[void]$text.AppendLine('        private static void Build()')
[void]$text.AppendLine('        {')
[void]$text.AppendLine('            blobs = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);')

foreach ($file in $files)
{
    $bytes = [System.IO.File]::ReadAllBytes($file.FullName)
    $base64 = [Convert]::ToBase64String($bytes)

    [void]$text.AppendLine()
    [void]$text.AppendLine("            // $($file.Name): $($bytes.Length) bytes")

    $chunks = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $base64.Length; $i += 92)
    {
        $length = [Math]::Min(92, $base64.Length - $i)
        $chunks.Add('"' + $base64.Substring($i, $length) + '"')
    }

    [void]$text.AppendLine("            blobs[""$($file.Name)""] =")
    for ($i = 0; $i -lt $chunks.Count; ++$i)
    {
        $suffix = if ($i -eq $chunks.Count - 1) { ';' } else { ' +' }
        [void]$text.AppendLine('                ' + $chunks[$i] + $suffix)
    }
}

[void]$text.AppendLine('        }')
[void]$text.AppendLine('    }')
[void]$text.AppendLine('}')

[System.IO.File]::WriteAllText($Out, $text.ToString(), (New-Object System.Text.UTF8Encoding $false))

$raw = ($files | Measure-Object Length -Sum).Sum
Write-Output ("$Out  ({0} containers, {1:N0} KB of artwork)" -f $files.Count, ($raw / 1KB))
